  /** Установка модуля: создаёт недостающие страницы, существующие не трогает. */
  public function run(): void {
    $this->sync(FALSE);
  }

  /** $overwrite = TRUE: тексты и адреса существующих страниц заменяются на актуальные. */
  public function sync(bool $overwrite): void {
    if (!NodeType::load('page')) {
      return;
    }
    foreach ($this->pages() as $alias => [$title, $body, $weight]) {
      $node = $this->nodeByAlias($alias);
      if (!$node) {
        foreach (self::LEGACY as $old => $new) {
          if ($new === $alias && ($node = $this->nodeByAlias($old))) {
            break;
          }
        }
      }
      if ($node && !$overwrite) {
        continue;
      }
      if ($node) {
        $node->setTitle($title);
        $node->set('body', ['value' => $body, 'format' => $this->format()]);
        $node->set('path', ['alias' => $alias]);
        $node->setPublished();
        $node->save();
      }
      else {
        $node = Node::create([
          'type' => 'page', 'title' => $title, 'status' => 1, 'langcode' => 'ru',
          'body' => ['value' => $body, 'format' => $this->format()],
          'path' => ['alias' => $alias],
        ]);
        $node->save();
      }
      $this->menuLink('footer', $title, (int) $node->id(), $weight);
      if ($alias === '/o_nas') {
        $this->menuLink('main', $title, (int) $node->id(), -9);
      }
    }
    if ($overwrite) {
      foreach (self::RETIRED as $alias) {
        if ($node = $this->nodeByAlias($alias)) {
          $node->setUnpublished()->save();
          foreach ($this->menuLinks('footer', (int) $node->id()) as $link) {
            $link->delete();
          }
        }
      }
    }
  }

  protected function format(): string {
    return \Drupal::entityTypeManager()->getStorage('filter_format')->load('full_html') ? 'full_html' : 'basic_html';
  }

  protected function nodeByAlias(string $alias): ?Node {
    $found = \Drupal::entityTypeManager()->getStorage('path_alias')->loadByProperties(['alias' => $alias]);
    foreach ($found as $path) {
      if (preg_match('#^/node/(\d+)$#', (string) $path->getPath(), $m) && ($node = Node::load((int) $m[1]))) {
        return $node;
      }
    }
    return NULL;
  }

  protected function menuLinks(string $menu, int $nid): array {
    if (!\Drupal::entityTypeManager()->getStorage('menu')->load($menu)) {
      return [];
    }
    return \Drupal::entityTypeManager()->getStorage('menu_link_content')->loadByProperties([
      'menu_name' => $menu, 'link__uri' => 'internal:/node/' . $nid,
    ]);
  }

  protected function menuLink(string $menu, string $title, int $nid, int $weight): void {
    if (!\Drupal::entityTypeManager()->getStorage('menu')->load($menu)) {
      return;
    }
    if ($links = $this->menuLinks($menu, $nid)) {
      foreach ($links as $link) {
        $link->set('title', $title)->set('weight', $weight)->save();
      }
      return;
    }
    \Drupal::entityTypeManager()->getStorage('menu_link_content')->create([
      'title' => $title, 'link' => ['uri' => 'internal:/node/' . $nid], 'menu_name' => $menu, 'weight' => $weight,
    ])->save();
  }

  protected function pages(): array {
    return [
