<?php

namespace Drupal\stroykroy_shop;

use Drupal\node\Entity\Node;
use Drupal\node\Entity\NodeType;

/**
 * Страницы магазина (контакты, реквизиты, оферта, политика). Это ЧЕРНОВИКИ: в квадратных скобках
 * вставьте свои данные, юридические тексты лучше показать юристу. Уже существующие страницы не перезаписываются.
 */
class StorePages {

  public function run(): void {
    if (!NodeType::load('page')) {
      return;
    }
    foreach ($this->pages() as $alias => [$title, $body, $weight]) {
      $exists = \Drupal::entityTypeManager()->getStorage('path_alias')->loadByProperties(['alias' => $alias]);
      if ($exists) {
        continue;
      }
      $node = Node::create([
        'type' => 'page', 'title' => $title, 'status' => 1, 'langcode' => 'ru',
        'body' => ['value' => $body, 'format' => $this->format()],
        'path' => ['alias' => $alias],
      ]);
      $node->save();
      $this->menuLink($title, $node->id(), $weight);
    }
  }

  protected function format(): string {
    return \Drupal::entityTypeManager()->getStorage('filter_format')->load('full_html') ? 'full_html' : 'basic_html';
  }

  protected function menuLink(string $title, $nid, int $weight): void {
    if (!\Drupal::entityTypeManager()->getStorage('menu')->load('footer')) {
      return;
    }
    \Drupal::entityTypeManager()->getStorage('menu_link_content')->create([
      'title' => $title, 'link' => ['uri' => 'internal:/node/' . $nid], 'menu_name' => 'footer', 'weight' => $weight,
    ])->save();
  }

  protected function pages(): array {
    $seller = 'Индивидуальный предприниматель [ФИО полностью] (далее — Продавец), ИНН [ИНН], ОГРНИП [ОГРНИП]';
    return [
      '/contacts' => ['Контакты', "<p>По вопросам заказов, оплаты и работы с файлами лекал пишите на почту: <a href=\"mailto:admin@stroykroy.com\">admin@stroykroy.com</a>.</p>"
        . "<p>Телефон: [телефон]. Мессенджеры: [Telegram / WhatsApp].</p><p>Отвечаем в рабочие дни, обычно в течение [одного рабочего дня].</p>"
        . "<p>$seller.</p><p>Подробные данные — на странице <a href=\"/requisites\">«Реквизиты»</a>.</p>", 1],
      '/requisites' => ['Реквизиты', "<p>$seller.</p><ul><li>Адрес: [адрес регистрации]</li><li>Расчётный счёт: [номер]</li><li>Банк: [название банка]</li><li>БИК: [БИК]</li><li>Корреспондентский счёт: [номер]</li><li>Эл. почта: admin@stroykroy.com</li><li>Телефон: [телефон]</li></ul>", 2],
      '/oferta' => ['Публичная оферта', $this->offer($seller), 3],
      '/privacy' => ['Политика конфиденциальности', $this->privacy($seller), 4],
    ];
  }

  protected function offer(string $seller): string {
    return <<<HTML
<p><em>Черновик: перед публикацией проверьте у юриста и заполните данные в квадратных скобках.</em></p>
<h2>1. Общие положения</h2>
<p>1.1. Настоящая оферта — предложение $seller заключить договор купли-продажи цифровых товаров (файлов лекал одежды) через сайт https://stroykroy.com (далее — Сайт).</p>
<p>1.2. Оформляя заказ и оплачивая его, Покупатель принимает условия настоящей оферты.</p>
<h2>2. Предмет договора</h2>
<p>2.1. Продавец передаёт Покупателю электронные файлы лекал (PDF для печати на листах А4, PDF в натуральную величину, DXF), построенные по параметрам, которые выбрал Покупатель: размер, мерки, прибавки, припуски на швы, элементы модели.</p>
<p>2.2. Лекала строятся автоматически по данным Покупателя. Продавец не отвечает за посадку изделия, если мерки и прибавки указаны неверно.</p>
<h2>3. Цена и оплата</h2>
<p>3.1. Цена указана на Сайте в рублях. Оплата — банковской картой и другими способами, доступными при оформлении заказа.</p>
<p>3.2. Договор считается заключённым с момента поступления оплаты.</p>
<h2>4. Передача товара</h2>
<p>4.1. Файлы передаются в электронном виде: ссылка для скачивания показывается на странице после оплаты и отправляется на электронную почту, указанную при заказе, как правило, в течение нескольких минут.</p>
<p>4.2. Покупатель обязан указать действующий адрес электронной почты. За неполученное письмо из-за ошибки в адресе или фильтра спама Продавец не отвечает; файлы можно скачать повторно по ссылке из письма.</p>
<h2>5. Использование файлов</h2>
<p>5.1. Файлы предоставляются для [личного использования и пошива изделий, в том числе на продажу — выбрать].</p>
<p>5.2. Запрещено передавать файлы третьим лицам, выкладывать их в открытый доступ, перепродавать и распространять в виде файлов.</p>
<h2>6. Возврат и претензии</h2>
<p>6.1. Файлы лекал изготавливаются по индивидуальным параметрам Покупателя, поэтому после передачи они возврату и обмену не подлежат, кроме случаев, указанных ниже.</p>
<p>6.2. Если файл не открывается или в нём ошибка по вине Продавца, Продавец бесплатно исправит файл или вернёт оплату. Для этого напишите на admin@stroykroy.com с номером заказа.</p>
<p>6.3. Претензии рассматриваются в течение [10] дней с момента получения.</p>
<h2>7. Прочие условия</h2>
<p>7.1. К отношениям сторон применяется право Российской Федерации.</p>
<p>7.2. Реквизиты Продавца — на странице <a href="/requisites">«Реквизиты»</a>.</p>
HTML;
  }

  protected function privacy(string $seller): string {
    return <<<HTML
<p><em>Черновик: перед публикацией проверьте у юриста и заполните данные в квадратных скобках.</em></p>
<h2>1. Оператор</h2>
<p>Оператор персональных данных — $seller. Контакты: admin@stroykroy.com.</p>
<h2>2. Какие данные мы собираем</h2>
<p>Адрес электронной почты, данные заказа (выбранные модели, размеры и мерки, указанные при построении лекал), технические данные (IP-адрес, сведения о браузере, файлы cookie).</p>
<h2>3. Зачем</h2>
<p>Чтобы принять и выполнить заказ, построить и передать файлы лекал, отправить письма о заказе, ответить на обращения и улучшать работу сайта.</p>
<h2>4. Основание</h2>
<p>Обработка выполняется с согласия пользователя, которое он даёт при оформлении заказа, и для исполнения договора.</p>
<h2>5. Передача третьим лицам</h2>
<p>Данные могут передаваться только тем, без кого заказ выполнить нельзя: платёжному сервису (ЮKassa), хостинг-провайдеру и почтовому сервису. Мы не продаём данные.</p>
<h2>6. Хранение и защита</h2>
<p>Данные хранятся на серверах на территории Российской Федерации в течение срока, необходимого для исполнения договора и требований закона, затем удаляются.</p>
<h2>7. Ваши права</h2>
<p>Вы можете запросить сведения о своих данных, их исправление или удаление и отозвать согласие, написав на admin@stroykroy.com.</p>
<h2>8. Файлы cookie</h2>
<p>Сайт использует файлы cookie для работы корзины и входа в личный кабинет, а также для статистики. Отключить cookie можно в настройках браузера, но корзина тогда работать не будет.</p>
<h2>9. Изменения</h2>
<p>Актуальная версия политики всегда опубликована на этой странице. Дата последнего изменения: [дата].</p>
HTML;
  }

}
