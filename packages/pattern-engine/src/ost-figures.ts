export interface StandardFigure {
  /** «рост-обхват груди-обхват бёдер», например «164-96-104» */
  id: string;
  group: 1 | 2 | 3 | 4;
  height: number;
  bust: number;
  hips: number;
  /** номер таблицы ОСТ */
  table: number;
  measurements: Measurements;
}

const r1 = (x: number) => Math.round(x * 10) / 10;

function build(): StandardFigure[] {
  const out: StandardFigure[] = [];
  for (const b of BLOCKS) {
    const heights = Object.keys(b.rows).map(Number).sort((x, y) => x - y);
    for (let i = 0; i < b.busts.length; i++) {
      for (const h of heights) {
        const [i0, i1] = b.rows[h];
        if (i < i0 || i > i1) continue;
        const v = {} as Record<OstKey, number>;
        OST_KEYS.forEach((k, n) => {
          const [a, db, dh] = [b.p[3 * n], b.p[3 * n + 1], b.p[3 * n + 2]] as Triple;
          v[k] = a + db * i + (dh * (h - 152)) / 6;
        });
        const m: Measurements = {
          rz7: r1(v[7]), rz9: r1(v[9]), rz12: r1(v[12]),
          rz13: r1(2 * v[13]), rz14: r1(2 * v[14]), rz15: r1(2 * v[15]),
          rz18: r1(2 * v[18]), rz19: r1(2 * v[19]),
          rz34: r1(v[34]), rz35: r1(v[35]), rz36: r1(v[36]), rz38: r1(v[38]), rz39: r1(v[39]), rz40: r1(v[40]),
          rz44: r1(v[43] + v[61]),
          rz45: r1(2 * v[45]), rz46: r1(2 * v[46]), rz47: r1(2 * v[47]),
          rz57: r1(v[57]),
        };
        out.push({ id: `${h}-${b.busts[i]}-${b.hips[i]}`, group: b.group, height: h, bust: b.busts[i], hips: b.hips[i], table: b.table, measurements: m });
      }
    }
  }
  return out;
}

/** Все типовые фигуры из таблиц 4-12: по полнотным группам, затем по обхвату груди и росту. */
export const STANDARD_FIGURES: StandardFigure[] = build().sort(
  (a, b) => a.group - b.group || a.bust - b.bust || a.height - b.height || a.hips - b.hips
);

export const STANDARD_FIGURE_GROUPS: { group: 1 | 2 | 3 | 4; title: string; figures: StandardFigure[] }[] = ([1, 2, 3, 4] as const).map((g) => ({
  group: g,
  title: `Полнотная группа ${g}`,
  figures: STANDARD_FIGURES.filter((f) => f.group === g),
}));

export function getStandardFigure(id: string): StandardFigure | undefined {
  return STANDARD_FIGURES.find((f) => f.id === id);
}

/** Какая типовая фигура сейчас выставлена: совпадают все 19 мерок. null — «свои мерки». */
export function findStandardFigure(m: Measurements): StandardFigure | null {
  const keys = Object.keys(m) as (keyof Measurements)[];
  return STANDARD_FIGURES.find((f) => keys.every((k) => Math.abs(f.measurements[k] - m[k]) < 0.005)) ?? null;
}
