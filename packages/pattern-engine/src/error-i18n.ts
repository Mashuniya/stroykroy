/**
 * Переводит типичные "сырые" сообщения об ошибках JavaScript на русский.
 * Используется и в formula-engine.ts (таблица формул ЕМКО), и в
 * leko/script-runner.ts (скрипт-редактор) — одно место перевода на оба движка.
 *
 * Свои собственные ошибки (те, что мы сами пишем через throw new Error("..."))
 * уже на русском и проходят через эту функцию без изменений (ни один паттерн
 * ниже на них не сработает).
 */
export function localizeError(e: unknown): string {
  const raw = e instanceof Error ? e.message : String(e);

  let m = raw.match(/Cannot read propert(?:y|ies) of undefined \(reading '(.+)'\)/);
  if (m) return `Обращение к несуществующему значению — свойство "${m[1]}" не найдено. Обычно это значит, что точка/значение, от которого вы зависите, не была построена на предыдущем шаге (там своя ошибка — см. выше).`;

  m = raw.match(/Cannot read propert(?:y|ies) of null \(reading '(.+)'\)/);
  if (m) return `Обращение к пустому значению (null) — свойство "${m[1]}" не найдено.`;

  m = raw.match(/^(.+) is not a function$/);
  if (m) return `"${m[1]}" не является функцией/оператором — проверьте написание названия.`;

  m = raw.match(/^(.+) is not defined$/);
  if (m) return `Переменная или оператор "${m[1]}" не определены — проверьте написание или порядок объявления (переменная должна быть объявлена ВЫШЕ того места, где используется).`;

  m = raw.match(/^Unexpected token (.+)$/);
  if (m) return `Синтаксическая ошибка рядом с "${m[1]}" — проверьте скобки, запятые, кавычки.`;

  if (/Unexpected end of input/.test(raw)) {
    return "Синтаксическая ошибка — не хватает закрывающей скобки или кавычки (неожиданный конец кода).";
  }

  m = raw.match(/^Assignment to constant variable\.?$/);
  if (m) return "Попытка изменить значение переменной, объявленной через const — используйте let, если переменная должна меняться.";

  // Не распознали — отдаём как есть (это, скорее всего, уже наше собственное русское сообщение).
  return raw;
}
