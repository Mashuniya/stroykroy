/**
 * Разбор числа, которое человек печатает в поле: принимает и точку, и запятую («0,5»), минус, пробелы.
 * Возвращает null, пока ввод ещё не стал числом (пусто, «-», «.», «0.» считается числом 0).
 * Нужен, чтобы поле можно было стереть и набрать «0», «0.5», «12,3», не получая подставленного нуля.
 */
export function parseDecimalInput(text: string): number | null {
  const t = text.replace(/\s+/g, "").replace(",", ".");
  if (t === "" || t === "-" || t === "." || t === "-.") return null;
  if (!/^-?\d*\.?\d*$/.test(t)) return null;
  const n = Number(t);
  return Number.isFinite(n) ? n : null;
}
